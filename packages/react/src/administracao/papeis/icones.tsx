// Ícones Lucide (estilos.md §6) usados na tela de papéis: traço 1.5, currentColor, decorativos.
import type { ReactNode } from 'react';

interface IconeProps {
  tamanho?: number;
}

function Svg({ tamanho = 16, children }: IconeProps & { children: ReactNode }) {
  return (
    <svg
      width={tamanho}
      height={tamanho}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

