import type { ReactNode } from 'react';

// Icons of the form controls, drawn with Lucide (ISC) strokes, estilos.md §6:
// currentColor, 1.5 to 2 stroke. They live here, private, so the controls do not depend on an icon library.

interface IconProps {
  /** Side in px. Default: 16 (14 in small buttons, 12 next to 12px text). */
  size?: 12 | 14 | 16;
  className?: string;
}

function Svg({ size = 16, className, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      className={className ? `fc-icon ${className}` : 'fc-icon'}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={size === 16 ? 1.5 : 2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

